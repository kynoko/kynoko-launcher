# Strings of ours that Tauri's files do not have: added, in every language.
NEW_KEYS = {'updateApp'}

HEADER = (f"; Tauri {VERSION}'s installer strings for this language (tauri-bundler, MIT\n"
          "; or Apache-2.0), with Kynoko Launcher's wording on the pages where an\n"
          "; installed version meets a new one, and on the uninstaller's box.\n"
          "; GENERATED by tools/nsis-installer.py: edit that script, not this file.\n")

os.makedirs(OUT_LANG, exist_ok=True)
files = {}
for lang in LANGUAGES:
    over = OVERRIDES[lang]
    missing_new = NEW_KEYS - set(over)
    if missing_new:
        sys.exit(f'nsis-installer: {lang} lacks {missing_new}')
    lines, seen, lang_id = [], set(), None
    for line in fetch(f'{BASE}/languages/{lang}.nsh').splitlines():
        m = re.match(r'LangString (\w+) (\$\{LANG_\w+\}) "(.*)"$', line)
        if m:
            lang_id = m.group(2)
            if m.group(1) in over:
                line = f'LangString {m.group(1)} {lang_id} "{over[m.group(1)]}"'
                seen.add(m.group(1))
        lines.append(line)
    for key in sorted(NEW_KEYS):
        lines.append(f'LangString {key} {lang_id} "{over[key]}"')
        seen.add(key)
    unknown = set(over) - seen
    if unknown:
        sys.exit(f'nsis-installer: {lang}: Tauri {VERSION} has no {unknown}')
    # No BOM: Tauri adds one when it copies the file (two make makensis fail).
    open(os.path.join(OUT_LANG, f'{lang}.nsh'), 'w', encoding='utf-8', newline='\n').write(HEADER + '\n'.join(lines) + '\n')
    files[lang] = f'windows/lang/{lang}.nsh'

# ---------------------------------------------------------------- config
conf = open(CONF, encoding='utf-8').read()
if '"template"' not in conf:
    conf = replace_once(conf, '        "installMode": "currentUser",', '        "installMode": "currentUser",\n        "template": "windows/installer.nsi",', 'tauri.conf template')
    json.loads(conf)
    open(CONF, 'w', encoding='utf-8', newline='\n').write(conf)
print(f'Tauri {VERSION}: windows/installer.nsi and {len(files)} language files written.')
