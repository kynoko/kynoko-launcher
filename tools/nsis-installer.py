#!/usr/bin/env python3
"""The Windows installer: Tauri's own NSIS template and language files, at
the version of the Tauri CLI in use, with Kynoko Launcher's changes.

Usage: python tools/nsis-installer.py   (after `npm ci` in app/; network)

Writes app/src-tauri/windows/installer.nsi and windows/lang/<Language>.nsh,
which tauri.conf.json points to (bundle.windows.nsis.template and
customLanguageFiles). Run it again after upgrading @tauri-apps/cli: every
change below is checked to still apply, and the script stops if one does not.

WHY. Installed over an existing version, Tauri's page offers two ways of
INSTALLING ("uninstall before installing" / "do not uninstall"), which read
as a riddle, and its same-version "Uninstall" uninstalls then reinstalls.
Here the page offers what a user expects: update (or reinstall), or
uninstall, the latter a real uninstall that ends the installer. Installing an
OLDER version keeps Tauri's page.
"""
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
APP = os.path.join(ROOT, 'app')
TAURI = os.path.join(APP, 'src-tauri')
OUT_TEMPLATE = os.path.join(TAURI, 'windows', 'installer.nsi')
OUT_LANG = os.path.join(TAURI, 'windows', 'lang')
CONF = os.path.join(TAURI, 'tauri.conf.json')

VERSION = json.load(open(os.path.join(APP, 'node_modules', '@tauri-apps', 'cli', 'package.json'), encoding='utf-8'))['version']
BASE = f'https://raw.githubusercontent.com/tauri-apps/tauri/tauri-cli-v{VERSION}/crates/tauri-bundler/src/bundle/windows/nsis'
LANGUAGES = ['French', 'English', 'Spanish', 'Japanese', 'SimpChinese', 'TradChinese', 'Arabic']


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read().decode('utf-8').lstrip('﻿')


def replace_once(text, old, new, what):
    if text.count(old) != 1:
        sys.exit(f'nsis-installer: "{what}" no longer applies to Tauri {VERSION}\'s template; update tools/nsis-installer.py.')
    return text.replace(old, new, 1)


# ---------------------------------------------------------------- template
template = fetch(f'{BASE}/installer.nsi')

template = replace_once(template, '''  ${ElseIf} $R0 = 1
    StrCpy $R1 "$(olderOrUnknownVersionInstalled)"
    StrCpy $R2 "$(uninstallBeforeInstalling)"
    StrCpy $R3 "$(dontUninstall)"''', '''  ${ElseIf} $R0 = 1
    ; Kynoko Launcher: update, or uninstall (tools/nsis-installer.py).
    StrCpy $R1 "$(olderOrUnknownVersionInstalled)"
    StrCpy $R2 "$(updateApp)"
    StrCpy $R3 "$(uninstallApp)"''', 'upgrade page choices')

template = replace_once(template, '''  ${If} $R0 = 0 ; Same version, proceed
    ${If} $R1 = 1              ; User chose to add/reinstall
      Goto reinst_done
    ${Else}                    ; User chose to uninstall
      Goto reinst_uninstall
    ${EndIf}
  ${ElseIf} $R0 = 1 ; Upgrading
    ${If} $R1 = 1              ; User chose to uninstall
      Goto reinst_uninstall
    ${Else}
      Goto reinst_done         ; User chose NOT to uninstall
    ${EndIf}''', '''  ; Kynoko Launcher (tools/nsis-installer.py): same version or upgrade,
  ; the first choice installs over the existing one (the user's preferences
  ; are kept), the second is a REAL uninstall that ends this installer.
  ${If} $R0 = 0 ; Same version
  ${OrIf} $R0 = 1 ; Upgrading
    ${If} $R1 = 1
      Goto reinst_done
    ${Else}
      Goto kynoko_uninstall
    ${EndIf}''', 'same-version and upgrade choices')

template = replace_once(template, '''  reinst_uninstall:
    HideWindow''', '''  ; A real uninstall, as from Windows' settings: the uninstaller copies
  ; itself out of the install folder and runs from there, so the launcher's
  ; cleanup runs (windows/hooks.nsh), with its "also delete my preferences"
  ; box. Nothing is installed afterwards. (Falling through from above keeps
  ; going where Tauri's code went.)
  Goto reinst_uninstall
  kynoko_uninstall:
    ReadRegStr $R1 SHCTX "${UNINSTKEY}" "UninstallString"
    Exec '$R1'
    Quit

  reinst_uninstall:
    HideWindow''', 'uninstall label')

header = (f'; Tauri {VERSION}\'s NSIS installer template (tauri-bundler, MIT or Apache-2.0),\n'
          '; with Kynoko Launcher\'s changes to the "already installed" page. GENERATED by\n'
          '; tools/nsis-installer.py: edit that script, not this file.\n')
os.makedirs(os.path.dirname(OUT_TEMPLATE), exist_ok=True)
open(OUT_TEMPLATE, 'w', encoding='utf-8', newline='\n').write(header + template)

# ---------------------------------------------------------------- strings
# Only what the pages above show, and the uninstaller's box. No em dash.
