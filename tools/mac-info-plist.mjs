#!/usr/bin/env node
/**
 * Writes app/src-tauri/Info.mac.plist, merged into the macOS bundle's
 * Info.plist (tauri.conf.json bundle.macOS.infoPlist):
 *
 * - CFBundleDocumentTypes: every file type of the catalogue, as an
 *   "Alternate" handler. macOS only lets an application become the default
 *   for types it declares, and it reads them from the bundle: a type added
 *   to the catalogue later needs a new build (docs/SPEC.md, section 7).
 * - CFBundleURLTypes: the kynoko-launcher:// scheme.
 *
 * Usage: node tools/mac-info-plist.mjs   (reads app/src-tauri/catalogue.json)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', 'app', 'src-tauri');
const catalogue = JSON.parse(readFileSync(join(dir, 'catalogue.json'), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const types = catalogue.apps
  .map((app) => {
    const exts = [...new Set((app.facades ?? []).flatMap((f) => (f.files ?? []).map((x) => x.ext)))];
    if (!exts.length) return '';
    const name = app.names?.en ?? app.code;
    return `      <dict>
        <key>CFBundleTypeName</key><string>${esc(name)}</string>
        <key>CFBundleTypeRole</key><string>Editor</string>
        <key>LSHandlerRank</key><string>Alternate</string>
        <key>CFBundleTypeExtensions</key>
        <array>${exts.map((e) => `<string>${esc(e)}</string>`).join('')}</array>
      </dict>`;
  })
  .filter(Boolean)
  .join('\n');

const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by tools/mac-info-plist.mjs from catalogue.json: do not edit. -->
<plist version="1.0">
  <dict>
    <key>CFBundleDocumentTypes</key>
    <array>
${types}
    </array>
    <key>CFBundleURLTypes</key>
    <array>
      <dict>
        <key>CFBundleURLName</key><string>Kynoko Launcher</string>
        <key>CFBundleURLSchemes</key><array><string>kynoko-launcher</string></array>
      </dict>
    </array>
  </dict>
</plist>
`;
writeFileSync(join(dir, 'Info.mac.plist'), plist);
console.log(`Info.mac.plist: ${catalogue.apps.length} apps, scheme kynoko-launcher`);
